def update_database():
    if not os.path.exists(DB_PATH):
        print(f"Error: Database not found at {DB_PATH}")
        return

    try:
        conn = sqlite3.connect(DB_PATH)
        cursor = conn.cursor()
        
        total = len(TRANSLATIONS)
        count = 0
        
        print(f"Starting update of {total} poems...")
        
        for poem_id, translation in TRANSLATIONS.items():
            cursor.execute(
                "UPDATE poems SET translation_baihua = ? WHERE id = ?",
                (translation, poem_id)
            )
            count += 1
            if count % 10 == 0 or count == total:
                print(f"Progress: {count}/{total} updated.")
        
        conn.commit()
        print("Update completed successfully.")
        
    except sqlite3.Error as e:
        print(f"Database error: {e}")
    except Exception as e:
        print(f"An error occurred: {e}")
    finally:
        if conn:
            conn.close()

if __name__ == "__main__":
    update_database()
